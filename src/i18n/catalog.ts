export type UILanguage = 'es' | 'en';
export type LanguagePreference = UILanguage | 'auto';

export function resolveLanguage(
  preference: LanguagePreference,
  browserLanguage: string,
): UILanguage {
  return preference === 'es' || preference === 'en'
    ? preference
    : browserLanguage.toLowerCase().startsWith('es')
      ? 'es'
      : 'en';
}

/** Pure translation preserving dynamic placeholders and explicit English fragments. */
export function translateUI(raw: unknown, language: UILanguage): string {
  const text = String(raw ?? '');
  if (language === 'es') return text;
  const exact = (EN as Record<string, string>)[text];
  if (Object.prototype.hasOwnProperty.call(EN, text) && exact !== undefined) return exact;
  return EN_FRAGMENTS.reduce(
    (value, [pattern, translation]) => value.replace(pattern, translation),
    text,
  );
}
